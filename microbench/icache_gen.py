#!/usr/bin/env python3
"""Generate icache_bench.cu: i-cache capacity sweep for one SM.

One warp runs a straight-line body of N independent FADDs (8 rotating
accumulators via inline PTX asm volatile -> exactly one 16B SASS FADD each)
in an unroll-1 loop. Steady-state cycles/instruction vs code footprint
(N*16B) steps up when the body no longer fits in L0 / L1 i-cache.
"""

SIZES = [128, 256, 384, 512, 768, 1024, 1536, 2048, 3072, 4096,
         5120, 6144, 6656, 7168, 7680, 8192, 8704, 9216, 10240, 11264,
         12288, 16384, 24576, 32768]  # instructions (x16B)
REPS_POW = [3, 6, 9, 12, 14]  # powers of two available for REP macros

lines = ["// auto-generated by icache_gen.py — do not edit",
         "#include <cstdio>",
         "#include <cuda_runtime.h>",
         "",
         '#define A1(i) asm volatile("add.f32 %0, %0, 0f3F800000;" : "+f"(x##i));',
         "#define A8 A1(0) A1(1) A1(2) A1(3) A1(4) A1(5) A1(6) A1(7)"]
# REP macros: A8 * 2^k
prev = "A8"
for k in range(1, 13):  # up to A8 * 4096 = 32768 instructions
    name = f"R{8 * (1 << k)}"
    lines.append(f"#define {name} {prev} {prev}")
    prev = name

def body(n):
    """Express n instructions as a sum of available macro blocks."""
    out, rest = [], n
    for blk in [8 * (1 << k) for k in range(12, -1, -1)]:
        name = "A8" if blk == 8 else f"R{blk}"
        while rest >= blk:
            out.append(name)
            rest -= blk
    assert rest == 0, n
    return " ".join(out)

for n in SIZES:
    lines += [
        "",
        f"__global__ void __launch_bounds__(32) k_{n}(unsigned long long *cyc, float *sink, int reps) {{",
        "    float x0 = 1.f, x1 = 1.f, x2 = 1.f, x3 = 1.f,",
        "          x4 = 1.f, x5 = 1.f, x6 = 1.f, x7 = 1.f;",
        "    unsigned long long t0 = clock64();",
        "#pragma unroll 1",
        f"    for (int r = 0; r < reps; ++r) {{ {body(n)} }}",
        "    unsigned long long t1 = clock64();",
        "    if (threadIdx.x == 0) *cyc = t1 - t0;",
        "    sink[threadIdx.x] = x0 + x1 + x2 + x3 + x4 + x5 + x6 + x7;",
        "}",
    ]

lines += [
    "",
    "int main(int argc, char **argv) {",
    "    int reps = argc > 1 ? atoi(argv[1]) : 64;",
    "    unsigned long long *cyc; float *sink;",
    "    cudaMalloc(&cyc, sizeof(unsigned long long));",
    "    cudaMalloc(&sink, 32 * sizeof(float));",
    '    printf("%8s %10s %10s %12s\\n", "insts", "bytes", "cycles", "cyc/inst");',
    "    unsigned long long h;",
]
for n in SIZES:
    lines += [
        f"    k_{n}<<<1, 32>>>(cyc, sink, reps);  // warmup",
        f"    k_{n}<<<1, 32>>>(cyc, sink, reps);",
        "    cudaMemcpy(&h, cyc, sizeof(h), cudaMemcpyDeviceToHost);",
        f'    printf("%8d %10d %10llu %12.3f\\n", {n}, {n} * 16, h, (double)h / ((double){n} * reps));',
    ]
lines += [
    "    cudaError_t err = cudaGetLastError();",
    '    if (err != cudaSuccess) printf("ERROR: %s\\n", cudaGetErrorString(err));',
    "    return 0;",
    "}",
]

with open("icache_bench.cu", "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"generated icache_bench.cu: {len(SIZES)} kernels, "
      f"max footprint {SIZES[-1] * 16 // 1024} KiB")
